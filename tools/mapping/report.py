"""Collect the overnight training results into one Markdown report.

  uv run tools/mapping/report.py                 # writes REPORT.md
  uv run tools/mapping/report.py --pick-better   # prints train set name
  uv run tools/mapping/report.py --pick A B      # prints the better run
  uv run tools/mapping/report.py --main RUN      # per-field section for RUN

Reads data/mapping/train/runs/*/metrics.json (and export.json) and writes
data/mapping/train/REPORT.md. --pick-better compares p-filt-100-s0 and
p-all-100-s0 on challenge route-edit accuracy (dev breaks ties) and
prints train_filtered or train_all.
"""

import argparse
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRAIN = ROOT / "data" / "mapping" / "train"


def load(name: str) -> dict | None:
    p = TRAIN / "runs" / name / "metrics.json"
    return json.loads(p.read_text()) if p.exists() else None


def score(m: dict, split: str, f="route_edit") -> float:
    return m[split][f]["acc"] if m and split in m else -1.0


def better(x: str, y: str) -> str:
    """Run with the higher challenge route_edit; dev breaks ties."""
    mx, my = load(x), load(y)
    kx = (score(mx, "challenge"), score(mx, "dev"))
    ky = (score(my, "challenge"), score(my, "dev"))
    return y if ky > kx else x


def pick_better() -> str:
    return "train_all" if better("p-filt-100-s0", "p-all-100-s0") \
        == "p-all-100-s0" else "train_filtered"


def cell(m: dict, split: str, f: str) -> str:
    if not m or split not in m:
        return "-"
    x = m[split][f]
    return f"{x['acc']:.3f} [{x['ci95'][0]:.3f}, {x['ci95'][1]:.3f}]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pick-better", action="store_true")
    ap.add_argument("--pick", nargs=2)
    ap.add_argument("--main", default=None)
    a = ap.parse_args()
    if a.pick_better:
        print(pick_better())
        return
    if a.pick:
        print(better(*a.pick))
        return
    runs = sorted(p.parent.name for p in TRAIN.glob("runs/p-*/metrics.json"))
    L = ["# Overnight mapping training report", "",
         "Generated by tools/mapping/report.py from runs/*/metrics.json. "
         "Accuracy with Wilson 95 % intervals. route_edit = intent, routes "
         "and route-free items equal as multisets (order-free); exact = "
         "frame token sequence equal.", ""]
    ds = TRAIN / "ds-v1" / "counts.json"
    if ds.exists():
        L += ["## Data", "", "```", ds.read_text().strip(), "```", ""]
    L += ["## Parser runs", "",
          "| run | ds | train set | frac | seed | samples | best step | min | "
          "dev exact | dev route_edit | challenge exact | "
          "challenge route_edit | challenge cov@0.95 |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        m = load(r)
        ar = m["args"]
        L.append(
            f"| {r} | {ar['ds']} | {ar['train']} | {ar['frac']} | "
            f"{ar['seed']} | "
            f"{m['train_samples']} | {m['best_step']} | "
            f"{m['train_minutes']} | {cell(m, 'dev', 'exact')} | "
            f"{cell(m, 'dev', 'route_edit')} | "
            f"{cell(m, 'challenge', 'exact')} | "
            f"{cell(m, 'challenge', 'route_edit')} | "
            f"{m.get('challenge', {}).get('coverage_at_0.95', '-')} |")
    L.append("")
    main_run = a.main or ("p-filt-100-s0" if pick_better() ==
                          "train_filtered" else "p-all-100-s0")
    m = load(main_run)
    if m:
        L += [f"## Per-field accuracy ({main_run})", "",
              "| field | dev | challenge |", "|---|---|---|"]
        for f in ("intent", "sources", "targets", "invert", "scope",
                  "route_edit", "exact"):
            L.append(f"| {f} | {cell(m, 'dev', f)} | "
                     f"{cell(m, 'challenge', f)} |")
        L += ["", "Confidence curve (route_edit accuracy of the most "
              "confident fraction):", "",
              "| coverage | dev | challenge |", "|---|---|---|"]
        for (c, d), (_, ch) in zip(m["dev"]["confidence_curve"],
                                   m.get("challenge", m["dev"])
                                   ["confidence_curve"]):
            L.append(f"| {c} | {d} | {ch} |")
        L.append("")
    tag = "filt" if pick_better() == "train_filtered" else "all"
    seeds = [load(f"p-{tag}-100-s{s}") for s in (0, 1, 2)]
    seeds = [s for s in seeds if s]
    if len(seeds) > 1:
        L += ["## Seeds at 100 %", ""]
        for split in ("dev", "challenge"):
            v = [score(s, split) for s in seeds]
            L.append(f"- {split} route_edit: mean {statistics.mean(v):.4f}, "
                     f"sd {statistics.stdev(v):.4f}, n={len(v)}")
        L.append("")
    curve = [(f, load(f"p-{tag}-{f}-s0")) for f in ("25", "50", "100")]
    L += ["## Learning curve (same step budget)", "",
          "| fraction | samples | dev route_edit | challenge route_edit |",
          "|---|---|---|---|"]
    for f, cm in curve:
        if cm:
            L.append(f"| {f} % | {cm['train_samples']} | "
                     f"{cell(cm, 'dev', 'route_edit')} | "
                     f"{cell(cm, 'challenge', 'route_edit')} |")
    L.append("")
    ps = TRAIN / "runs" / "ps-v1" / "metrics.json"
    if ps.exists():
        L += ["## param-sense v1", "", "```", ps.read_text().strip(), "```",
              ""]
    for r in runs:
        au = TRAIN / "runs" / r / "audit.json"
        if au.exists():
            L += [f"## Label audit ({r})", "", "Share of training sentences "
                  "whose label the trained parser does not reproduce "
                  "(route_edit), split by the round-trip filter.", "", "```",
                  au.read_text().strip(), "```", ""]
    for r in runs:
        ex = TRAIN / "runs" / r / "export.json"
        if ex.exists():
            e = json.loads(ex.read_text())
            L += [f"## Export and latency ({r})", "", "```", json.dumps(
                {k: e[k] for k in ("params", "bytes", "latency_cpu",
                                   "rss_mb", "accuracy_by_weights",
                                   "machine")}, indent=1), "```", ""]
    (TRAIN / "REPORT.md").write_text("\n".join(L) + "\n")
    print(f"wrote {TRAIN / 'REPORT.md'}")


if __name__ == "__main__":
    main()
