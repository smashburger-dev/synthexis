"""Parameter counts per mapped plugin as the synthexis plugin picker sees
them, for debugging the FL bridge.

  uv run tools/mapping/fl_param_counts.py [--data DIR] [--out FILE]

Mapped plugins: every plugin id in the label runs export_completion.py
reads. For each, from the AU and VST3 harvests: named parameters, the
placeholders the picker drops (same rule as is_placeholder in
plugin/synthexis/src/fl.rs) and what is left. FL on macOS lists a plugin's
parameters like the AU harvest does (6 of 7 plugins measured on 11-03 match
it exactly; ShaperBox matches the automatable VST3 parameters), so the
expected count is the AU one, else the automatable VST3 one. Plugins
measured in FL get that count next to it.

Writes probes/fl-target-picker/param_counts.md (or --out).
"""

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "mapping"
OUT = ROOT / "probes" / "fl-target-picker" / "param_counts.md"
LABEL_RUNS = ["label-vst3-prio-v1", "label-vst3-bulk-v1", "label-prio-v1", "label-bulk-v1"]
FL_CC_FIRST = 4096
# names after the CC and placeholder filter, read from FL 26.1.7 on 11-03
# (probes/fl-target-picker/RESULT.md, Noa's test project)
FL_MEASURED = {
    "FabFilter/Pro-Q 3": 358,
    "Output/Portal": 143,
    "Cableguys/ShaperBox 3": 876,
    "Neural DSP/Archetype John Mayer X": 172,
    "Valhalla DSP, LLC/ValhallaFutureVerb": 24,
    "Valhalla DSP, LLC/ValhallaSupermassive": 14,
    "Xfer Records/Serum 2": 541,
}


def placeholder(name: str) -> str | None:
    """Family of a placeholder name, or None for a real parameter: the rule
    of is_placeholder in plugin/synthexis/src/fl.rs (test_mapping.py runs
    the fl.rs test cases through it). export_paramsense.py uses it too."""
    if any(ord(c) < 32 or ord(c) == 127 for c in name):
        return "control chars"
    n = name.strip().lower()
    if re.match(r"midi cc($|[ #0-9])", n) or re.match(r"cc[ #0-9]", n):
        return "midi cc"
    if re.search(r" chan \d+$", n):
        return "midi chan"
    if re.fullmatch(r"reserved ?\d*", n) or "(reserved)" in n:
        return "reserved"
    if n in ("unused", "internal"):
        return n
    return None


def count(path: Path, plugins: set[str], vst3: bool) -> dict[str, Counter]:
    out: dict[str, Counter] = defaultdict(Counter)
    for line in open(path, encoding="utf-8"):
        r = json.loads(line)
        pid = r["plugin_id"]
        if pid not in plugins or r["index"] >= FL_CC_FIRST:
            continue
        name = r["name"].strip()
        if not name:
            continue
        c = out[pid]
        if vst3 and r.get("class_name"):
            c["class:" + r["class_name"]] += 1
        c["named"] += 1
        fam = placeholder(name)
        if fam:
            c["drop:" + fam] += 1
            continue
        c["real"] += 1
        if vst3 and "can_automate" in r.get("flags", []) and "is_bypass" not in r.get("flags", []):
            c["auto"] += 1
    return out


def first_class(c: Counter) -> int:
    """VST3 harvests list every class of a bundle (Serum 2 and Serum 2 FX);
    counts are per class, so divide by the number of classes."""
    k = sum(1 for key in c if key.startswith("class:"))
    return max(k, 1)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(DATA))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    data = Path(a.data)
    mapped: set[str] = set()
    for run in LABEL_RUNS:
        for line in open(data / "labels" / run / "labels.jsonl", encoding="utf-8"):
            mapped.add(json.loads(line)["plugin_id"])
    au = count(data / "harvest" / "au" / "params.jsonl", mapped, vst3=False)
    v3 = count(data / "harvest" / "vst3" / "params.jsonl", mapped, vst3=True)

    rows, fams, agree = [], Counter(), []
    for pid in sorted(mapped, key=str.casefold):
        ca, cv = au.get(pid, Counter()), v3.get(pid, Counter())
        k = first_class(cv)
        for key, v in list(ca.items()) + [(x, y // k) for x, y in cv.items()]:
            if key.startswith("drop:"):
                fams[key[5:]] += v
        expect = ca["real"] if ca else cv["auto"] // k if cv else None
        fl = FL_MEASURED.get(pid)
        if fl is not None:
            agree.append((pid, fl, ca["real"] if ca else None, cv["auto"] // k if cv else None))
        dropped = ", ".join(f"{key[5:]} {v}" for key, v in sorted(ca.items() or cv.items()) if key.startswith("drop:"))
        rows.append((pid, ca["named"] if ca else "", ca["real"] if ca else "",
                     cv["named"] // k if cv else "", cv["auto"] // k if cv else "",
                     expect if expect is not None else "", fl if fl is not None else "", dropped))

    lines = [
        "# Parameter counts of the mapped plugins",
        "",
        "Generated by `tools/mapping/fl_param_counts.py` from the AU and VST3 harvests",
        "and the label runs. \"real\" leaves out FL's CC entries (index 4096 and up) and",
        "the placeholders the picker drops (`is_placeholder` in",
        "`plugin/synthexis/src/fl.rs`). \"expected in FL\" is the AU count, else the",
        "automatable VST3 count; \"FL\" is measured in FL 26.1.7 on 11-03.",
        "",
        f"{len(rows)} mapped plugins, {len(au)} with an AU harvest, {len(v3)} with a VST3 harvest.",
        "Dropped placeholders over all of them: "
        + ", ".join(f"{f} {n:,}" for f, n in fams.most_common()) + ".",
        "",
        "Measured in FL against the harvests:",
        "",
        "| Plugin | FL | AU real | VST3 automatable |",
        "|---|---|---|---|",
    ]
    lines += [f"| {p} | {fl} | {au_r} | {v_r} |" for p, fl, au_r, v_r in agree]
    lines += [
        "",
        "| Plugin | AU named | AU real | VST3 named | VST3 automatable | expected in FL | FL | dropped (AU, else VST3) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    hits = sum(1 for _, fl, au_r, v_r in agree if fl in (au_r, v_r))
    print(f"{len(rows)} plugins -> {a.out}; FL-measured matches {hits}/{len(agree)}; dropped {dict(fams)}")


if __name__ == "__main__":
    main()
