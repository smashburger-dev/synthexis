"""Checks the expanded real-sentence set (Noa's sentences plus derived ones)
and writes a review list. Reads only; the set itself is eval data under
data/mapping/eval/ and is never committed or trained on.

  uv run probes/real-eval/check.py

1. originals:  every line of eval.txt appears once as kind 'orig', verbatim
2. groups:     every row has its group's split; style rows take their frame
               from a group of the same split
3. params:     every named target parameter exists in the harvest of the
               row's plugin (VST3 or AU)
4. duplicates: no two rows with the same normalised text
5. overlap:    word 5-grams and closest sentence pairs across the
               calibration / eval border
6. counts:     split x kind x language, sentences with ß
Writes data/mapping/eval/review.md, one block per group.
"""

import collections
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVAL = ROOT / "data" / "mapping" / "eval"
HARVEST = ROOT / "data" / "mapping" / "harvest"


def norm(t: str) -> str:
    return " ".join(re.findall(r"\w+", t.casefold()))


def grams(t: str, n: int = 5) -> set:
    w = norm(t).split()
    return {" ".join(w[i:i + n]) for i in range(len(w) - n + 1)}


def harvest() -> dict:
    names = collections.defaultdict(set)
    for kind in ("vst3", "au"):
        for line in open(HARVEST / kind / "params.jsonl"):
            p = json.loads(line)
            names[p["plugin_id"]].add(p["name"])
    return names


def check(lines: list, rows: list, names: dict) -> int:
    bad = []
    orig = {r["src"]: r for r in rows if r["kind"] == "orig"}
    for i, text in enumerate(lines, 1):
        if i not in orig or orig[i]["text"] != text:
            bad.append(f"eval.txt line {i} missing or changed in expanded.jsonl")
    split = {r["group"]: r["split"] for r in orig.values()}
    group = {r["src"]: r["group"] for r in orig.values()}
    seen = {}
    for r in rows:
        if split.get(r["group"]) != r["split"]:
            bad.append(f"{r['id']}: split differs from its group")
        if "style_from" in r and r["style_from"] not in group:
            bad.append(f"{r['id']}: style frame from line {r['style_from']}, which has no original row")
        elif "style_from" in r and split[group[r["style_from"]]] != r["split"]:
            bad.append(f"{r['id']}: style frame from the other split")
        for p in r["params"]:
            if r["plugin"] not in names or p not in names[r["plugin"]]:
                bad.append(f"{r['id']}: '{p}' not in the harvest of {r['plugin']}")
        k = norm(r["text"])
        if k in seen:
            bad.append(f"{r['id']}: same text as {seen[k]}")
        seen[k] = r["id"]
    for b in bad:
        print("  FAIL", b)
    return len(bad)


def overlap(rows: list) -> None:
    cal = [r for r in rows if r["split"] == "calibration"]
    ev = [r for r in rows if r["split"] == "eval"]
    share = sum(bool(grams(e["text"]) & set().union(*(grams(c["text"]) for c in cal)))
                for e in ev)
    near = sorted((max((difflib.SequenceMatcher(None, norm(e["text"]).split(),
                                                norm(c["text"]).split()).ratio(), c["id"])
                       for c in cal) + (e["id"],) for e in ev), reverse=True)
    print(f"\n5. eval rows sharing a word 5-gram with calibration: {share} of {len(ev)}; "
          f"closest pairs (word sequence ratio): " + ", ".join(
              f"{e} ~ {c} {s:.2f}" for s, c, e in near[:5]))


def counts(rows: list) -> None:
    c = collections.Counter((r["split"], r["kind"], r["lang"]) for r in rows)
    print("\n6. counts")
    for sp in ("calibration", "eval"):
        rs = [r for r in rows if r["split"] == sp]
        per = ", ".join(f"{k} {c[sp, k, 'en']}/{c[sp, k, 'de']}"
                        for k in ("orig", "translate", "swap", "style"))
        print(f"   {sp}: {len(rs)} rows, {len({r['group'] for r in rs})} groups "
              f"(en/de: {per}); with ß {sum('ß' in r['text'] for r in rs)}")
    by = collections.Counter(r["plugin"] or "unknown" for r in rows if r["kind"] == "orig")
    print("   context plugin of the originals:", ", ".join(
        f"{k.split('/')[-1]} {v}" for k, v in by.most_common()))


def review(rows: list) -> None:
    out = ["# Review: Noa's sentences and derived ones",
           "",
           "Generated by probes/real-eval/check.py. Edit expanded.jsonl, not this file.",
           "Check per derived row: sounds like you, same meaning plus the listed change,",
           "plugin and parameter right. Kinds: o = yours, t = translation, s = slot swap,",
           "y = your request frame from another sentence."]
    for g in sorted({r["group"] for r in rows}):
        rs = [r for r in rows if r["group"] == g]
        out += ["", f"## group {g} ({rs[0]['split']})"]
        for r in rs:
            plug = (r["plugin"] or "plugin?").split("/")[-1]
            extra = "; ".join(filter(None, [
                ", ".join(r["delta"]), f"frame of {r['style_from']:02d}-o"
                if "style_from" in r else "", f"{plug}: {', '.join(r['params'])}"
                if r["params"] else plug, r["note"]]))
            out.append(f"- `{r['id']}` {r['text']}  \n  _{extra}_")
    (EVAL / "review.md").write_text("\n".join(out) + "\n")


def main() -> None:
    lines = [line.rstrip("\n") for line in open(EVAL / "eval.txt") if line.strip()]
    rows = [json.loads(line) for line in open(EVAL / "expanded.jsonl")]
    print(f"{len(lines)} sentences by Noa, {len(rows)} rows in expanded.jsonl")
    print("\n1-4. originals, groups, params, duplicates")
    n = check(lines, rows, harvest())
    print("   all pass" if not n else f"   {n} failures")
    overlap(rows)
    counts(rows)
    review(rows)
    print("\nreview list: data/mapping/eval/review.md")
    sys.exit(1 if n else 0)


if __name__ == "__main__":
    main()
